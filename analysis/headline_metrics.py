"""Every number quoted in README.md, the resume kit and the web dashboard comes from here.

Run after the pipeline. Writes output_marts/headline_metrics.json and rewrites the block
between the METRICS markers in README.md, so the prose cannot drift from the data.
tests/test_pulserx.py fails if README.md and the JSON disagree.

Two kinds of number, kept apart:
  * ARITHMETIC -- counted straight from the marts (coverage, call gaps, capacity).
  * SCENARIO   -- depends on an assumed response to an extra call; the data has no
                  call-response signal. Reported as a range, never as a finding.
"""
import json
import math
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "alteryx"))
from run_pipeline import (ASSUMED_TRX_PER_EXTRA_CALL, NET_REVENUE_PER_TRX_USD,  # noqa: E402
                          TIER_DECILE_MIN)

START, END = "<!-- METRICS:START -->", "<!-- METRICS:END -->"


def compute(marts="output_marts", data="data"):
    h = pd.read_csv(os.path.join(marts, "tableau_hcp_targeting_mart.csv"))
    t = pd.read_csv(os.path.join(marts, "tableau_territory_alignment_mart.csv"))
    reps = pd.read_csv(os.path.join(data, "raw_sales_reps.csv"))
    n_rx = sum(1 for _ in open(os.path.join(data, "raw_monthly_rx_claims.csv"), encoding="utf-8")) - 1

    calls = int(h["Total_Calls_2025"].sum())
    high = h["Market_Decile"] >= TIER_DECILE_MIN
    tier = h["Targeting_Tier"].str[:6]
    t12 = tier.isin(["Tier 1", "Tier 2"])
    surplus = (-h["Call_Deficit"]).clip(lower=0)
    deficit = h["Call_Deficit"].clip(lower=0)
    top = h.sort_values("Annual_Market_TRx", ascending=False)
    capacity = int(t["Target_Call_Capacity"].sum())
    required = int(h["Recommended_Annual_Calls"].sum())
    per_call_rep = int(reps["Annual_Call_Capacity"].iloc[0])

    t12_deficit = int(deficit[t12].sum())
    # Scenario: move surplus calls onto the Tier 1-2 gap, value each added call at the assumed response
    moved = min(t12_deficit, int(surplus.sum()))
    base_trx = moved * ASSUMED_TRX_PER_EXTRA_CALL["high_decile"]
    base_usd = base_trx * NET_REVENUE_PER_TRX_USD
    brand_sales = float(h["Annual_PulseRx_Sales_USD"].sum())

    return {
        "arithmetic": {
            "hcps": len(h), "rx_rows": n_rx, "crm_calls": calls,
            "territories": len(t), "reps": len(reps), "calls_per_rep_capacity": per_call_rep,
            "top20pct_hcps_share_of_market_trx_pct": round(
                100 * top["Annual_Market_TRx"].head(len(h) // 5).sum() / h["Annual_Market_TRx"].sum(), 1),
            "high_value_hcps": int(high.sum()),
            "high_value_hcps_with_zero_calls": int((high & (h["Total_Calls_2025"] == 0)).sum()),
            "high_value_hcps_with_zero_calls_pct": round(
                100 * (high & (h["Total_Calls_2025"] == 0)).sum() / high.sum(), 1),
            "calls_on_deciles_1_4_pct": round(100 * h.loc[h["Market_Decile"] <= 4, "Total_Calls_2025"].sum() / calls, 1),
            "tier_counts": {k: int(v) for k, v in h["Targeting_Tier"].value_counts().sort_index().items()},
            "tier4_calls_beyond_plan": int(surplus[tier == "Tier 4"].sum()),
            "calls_beyond_plan_all_tiers": int(surplus.sum()),
            "tier1_2_call_shortfall": t12_deficit,
            "plan_required_calls": required,
            "field_capacity_calls": capacity,
            "plan_utilization_pct": round(100 * required / capacity, 1),
            "reps_needed_for_plan": math.ceil(required / per_call_rep),
            "territory_actions": {k: int(v) for k, v in t["Sizing_Consulting_Action"].value_counts().sort_index().items()},
            "brand_sales_usd": round(brand_sales),
        },
        "scenario": {
            "assumed_trx_per_extra_call_high_value": ASSUMED_TRX_PER_EXTRA_CALL["high_decile"],
            "net_revenue_per_trx_usd": NET_REVENUE_PER_TRX_USD,
            "calls_moved_to_tier1_2": moved,
            "incremental_sales_usd_low": round(base_usd * 0.5),
            "incremental_sales_usd_base": round(base_usd),
            "incremental_sales_usd_high": round(base_usd * 1.5),
            "base_as_pct_of_brand_sales": round(100 * base_usd / brand_sales, 1),
        },
    }


def render(m):
    a, s = m["arithmetic"], m["scenario"]
    act = a["territory_actions"]
    return "\n".join([
        START,
        "*Generated by `analysis/headline_metrics.py` from the current marts -- do not edit by hand.*",
        "",
        "| Arithmetic (counted from the data) | Value |",
        "|---|---|",
        f"| Prescribers / monthly Rx rows / CRM calls | {a['hcps']:,} / {a['rx_rows']:,} / {a['crm_calls']:,} |",
        f"| Territories / reps (capacity {a['calls_per_rep_capacity']} calls per rep) | {a['territories']} / {a['reps']} |",
        f"| Top 20% of prescribers' share of market TRx | {a['top20pct_hcps_share_of_market_trx_pct']}% |",
        f"| High-value prescribers (deciles 8-10) with **no call** in the year | "
        f"**{a['high_value_hcps_with_zero_calls']:,} of {a['high_value_hcps']:,}** ({a['high_value_hcps_with_zero_calls_pct']}%) |",
        f"| Calls to Tier 4 prescribers beyond their 1-call plan | {a['tier4_calls_beyond_plan']:,} |",
        f"| Calls beyond plan, all tiers | {a['calls_beyond_plan_all_tiers']:,} |",
        f"| Tier 1-2 call shortfall against plan | {a['tier1_2_call_shortfall']:,} |",
        f"| Calls the tiered plan needs vs field capacity | {a['plan_required_calls']:,} vs {a['field_capacity_calls']:,} "
        f"({a['plan_utilization_pct']}%) |",
        f"| Reps the plan needs vs reps today | {a['reps_needed_for_plan']} vs {a['reps']} |",
        f"| Territories: optimally sized / underutilized / overburdened | {act.get('Optimally Sized', 0)} / "
        f"{act.get('Underutilized (Expand Reach)', 0)} / {act.get('Overburdened (Carve Out Territory)', 0)} |",
        "",
        f"**Scenario, not a finding.** Moving {s['calls_moved_to_tier1_2']:,} surplus calls onto the Tier 1-2 "
        f"shortfall, at an *assumed* {s['assumed_trx_per_extra_call_high_value']} extra TRx per call and "
        f"${s['net_revenue_per_trx_usd']:,} per TRx: ${s['incremental_sales_usd_low'] / 1e6:.1f}M-"
        f"${s['incremental_sales_usd_high'] / 1e6:.1f}M (base ${s['incremental_sales_usd_base'] / 1e6:.1f}M, "
        f"{s['base_as_pct_of_brand_sales']}% of current brand sales). The data has no call-response signal, so "
        "the per-call response is an input, not a result.",
        END,
    ])


RESUME_START, RESUME_END = "<!-- RESUME:START -->", "<!-- RESUME:END -->"


def render_resume(m):
    a = m["arithmetic"]
    return "\n".join([
        RESUME_START,
        "```",
        "PulseRx -- HCP Targeting & Territory Sizing (synthetic data)        SQL, Python, DuckDB",
        f"- Built a decile and four-tier call plan for {a['hcps']:,} synthetic oncology prescribers in SQL and",
        "  Python, with tests that the two agree prescriber by prescriber.",
        f"- Found {a['high_value_hcps_with_zero_calls']} of {a['high_value_hcps']} high-value prescribers "
        f"({a['high_value_hcps_with_zero_calls_pct']:.0f}%) got no rep call while "
        f"{a['calls_beyond_plan_all_tiers']:,} calls went beyond plan",
        f"  elsewhere; the full plan needs {a['plan_utilization_pct']:.0f}% of current capacity "
        f"({a['reps_needed_for_plan']} of {a['reps']} reps) -- retarget, don't hire.",
        "```",
        RESUME_END,
    ])


def _replace_block(path, start, end, block):
    text = open(path, encoding="utf-8").read()
    i, j = text.index(start), text.index(end) + len(end)
    open(path, "w", encoding="utf-8").write(text[:i] + block + text[j:])


def write_readme(m, readme="README.md"):
    _replace_block(readme, START, END, render(m))


if __name__ == "__main__":
    m = compute()
    with open("output_marts/headline_metrics.json", "w", encoding="utf-8") as f:
        json.dump(m, f, indent=2)
    if os.path.exists("README.md") and START in open("README.md", encoding="utf-8").read():
        write_readme(m)
    kit = "private/RESUME_AND_INTERVIEW_KIT.md"  # local only (git-ignored)
    if os.path.exists(kit) and RESUME_START in open(kit, encoding="utf-8").read():
        _replace_block(kit, RESUME_START, RESUME_END, render_resume(m))
    print(json.dumps(m, indent=2))
